    def mark_attachment_sites(self, head_map, tail_map, leaving_element="H"):
        """Mark neutral terminal leaving atoms using RDKit atom-map identifiers.

        Parameters
        ----------
        head_map, tail_map : int
            Maps of the head and tail leaving atoms, or their anchor atoms.
            Anchors with multiple candidate leaving atoms are accepted only
            for equivalent hydrogens on a non-stereogenic center.
        leaving_element : str, default "H"
            Element of the neutral singly bonded leaving atoms.

        Raises
        ------
        ValueError
            If maps are absent, sites overlap, or a leaving atom is ambiguous,
            charged, or not terminal. Existing annotations remain unchanged.
        """
        mol = self.to_rdkit()
        by_map = {a.GetAtomMapNum(): a for a in mol.GetAtoms()}
        selected = []
        for number in (head_map, tail_map):
            if number not in by_map:
                raise ValueError(f"Atom map {number} is not present in the molecule.")
            atom = by_map[number]
            candidates = ([atom] if atom.GetSymbol() == leaving_element else
                          [a for a in atom.GetNeighbors() if a.GetSymbol() == leaving_element])
            candidates = [a for a in candidates if a.GetDegree() == 1 and a.GetFormalCharge() == 0
                          and mol.GetBondBetweenAtoms(a.GetIdx(), a.GetNeighbors()[0].GetIdx()).GetBondType() == Chem.BondType.SINGLE]
            if len(candidates) > 1:
                equivalent_h = leaving_element == "H" and len({a.GetIsotope() for a in candidates}) == 1
                if not equivalent_h or atom.GetChiralTag() != Chem.ChiralType.CHI_UNSPECIFIED:
                    raise ValueError(f"Ambiguous leaving atoms at map {number}; specify the leaving atom's map.")
            if not candidates:
                raise ValueError(f"Map {number} has no neutral terminal {leaving_element} leaving atom.")
            selected.append(candidates[0].GetIdx())
        if selected[0] == selected[1]:
            raise ValueError("Head and tail must select different leaving atoms.")
        marks = np.zeros(len(self.atoms), dtype=int)
        marks[selected] = [1, 2]
        self.atoms.set_array("polymerize", marks)

